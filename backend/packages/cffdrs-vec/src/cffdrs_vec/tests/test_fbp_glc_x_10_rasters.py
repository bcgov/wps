"""
Same 20 published GLC-X-10 FBP System test cases and the same calculate_primary_output() as
test_fbp_glc_x_10.py, but sourced from the GeoTIFF fixtures under fixtures/glc_x_10/ and
fixtures/glc_x_10_paper/ (generated by generate_glc_x_10_rasters.py, via GLCX10Source.
load_raster_inputs()) instead of the CSVs directly, showing cffdrs_vec.fbp's vectorized functions
also work correctly when driven by real GDAL raster reads (float32 storage, WPSDataset's nodata
handling) rather than plain float64 arrays parsed straight from CSV.

Parametrized over the same GLCX10Source objects as test_fbp_glc_x_10.py (see _glc_x_10_data.py),
so the tolerance divergence between them (paper's ROS/HFI/CFB need looser tolerance, see
test_fbp_glc_x_10.py for why) lives in exactly one place.
"""

import numpy as np
import pytest

from cffdrs_vec.tests._glc_x_10_data import GLC_X_10_SOURCES, calculate_primary_output


@pytest.mark.parametrize("source", GLC_X_10_SOURCES, ids=lambda s: s.name)
def test_raster_inputs_match_csv_inputs(source):
    """Sanity check that generate_glc_x_10_rasters.py's output hasn't drifted from the CSVs it
    was generated from - this would fail if the CSVs were updated without regenerating rasters.
    """
    raster_inputs = source.load_raster_inputs()
    csv_inputs, _expected = source.load()
    np.testing.assert_allclose(raster_inputs.fuel_type_codes, csv_inputs.fuel_type_codes)
    np.testing.assert_allclose(raster_inputs.ffmc, csv_inputs.ffmc)
    np.testing.assert_allclose(raster_inputs.bui, csv_inputs.bui)
    np.testing.assert_allclose(raster_inputs.cbh, csv_inputs.cbh)
    np.testing.assert_allclose(raster_inputs.cfl, csv_inputs.cfl)


@pytest.mark.parametrize("source", GLC_X_10_SOURCES, ids=lambda s: s.name)
def test_fbp_glc_x_10_rasters_ros(source):
    inputs = source.load_raster_inputs()
    expected = source.read_raster_output("ros")
    ros, _, _, _, _, _, _ = calculate_primary_output(inputs)
    np.testing.assert_allclose(ros, expected, rtol=source.rtol_ros_hfi, err_msg="ROS")


