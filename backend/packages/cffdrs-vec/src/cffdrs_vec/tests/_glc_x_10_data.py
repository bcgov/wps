"""
Shared loading/computation logic for the GLC-X-10 (Wotton et al. 2009) published FBP System test
cases, used by test_fbp_glc_x_10.py, test_fbp_glc_x_10_paper.py (read the vendored CSVs directly)
and test_fbp_glc_x_10_rasters.py (parametrized over both sources, reads the equivalent GeoTIFF
fixtures generated by generate_glc_x_10_rasters.py from those same CSVs). See
https://github.com/bcgov/wps/issues/4893.

The cffdrs_r_test_fbp_*.csv files in data/ are the CFFDRS working group's own digitized
transcription of the paper's Tables 4/5 - not something extracted from the PDF here. They're
copied from the R cffdrs package (github.com/cffdrs/cffdrs_r: data/test_fbp.csv,
tests/testthat/data/fbp_01.csv, fbp_04.csv), by way of cffdrs_py's own copy of those same files
(cffdrs/tests/data/test_fbp.csv, fbp_01.csv, fbp_04.csv - not included in the installed cffdrs_py
package, hence vendored here rather than depended on at runtime).

The glc_x_10_paper_*.csv files are a second, independent transcription: extracted directly from
Tables 4-6 of the published PDF (Fo123-2-10-2009-eng.pdf) via `pdftotext -layout`, without going
through the R package at all. They exist to cross-validate the R-sourced CSVs above against the
actual paper rather than trusting that chain of custody; see PaperGLCX10Cases. Two cells in
Table 4 (GS, rows 2/4) and several cells in Table 5 (row 4, and SF for row 2) contain two
overlapping/stacked values in the PDF's text layer, an apparent uncorrected draft artifact; the
later-positioned (second) value was used in both cases.

Not a test_*.py module on purpose, so pytest doesn't try to collect it.
"""

